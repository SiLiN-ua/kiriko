def _serialize_content(content_blocks):
    """Convert SDK content blocks → plain JSON-serializable dicts."""
    out = []
    for b in content_blocks:
        if b.type == 'text':
            out.append({'type': 'text', 'text': b.text})
        elif b.type == 'tool_use':
            out.append({
                'type': 'tool_use',
                'id': b.id,
                'name': b.name,
                'input': b.input,
            })
    return out


_TOOL_RESULT_MAX = 40_000   # chars per tool_result block
_MAX_TURNS       = 20       # max user+assistant pairs to keep

def _trim_messages(msgs: list) -> list:
    """
    1. Truncate oversized tool_result content blocks.
    2. If still too many turns — keep only the first message (file upload context)
       + last _MAX_TURNS pairs.
    """
    # Step 1: trim fat tool_result blocks
    trimmed = []
    for m in msgs:
        if m.get('role') != 'user' or not isinstance(m.get('content'), list):
            trimmed.append(m)
            continue
        new_content = []
        for block in m['content']:
            if isinstance(block, dict) and block.get('type') == 'tool_result':
                c = block.get('content', '')
                if isinstance(c, str) and len(c) > _TOOL_RESULT_MAX:
                    block = {**block, 'content': c[:_TOOL_RESULT_MAX] + '\n[...скорочено...]'}
            new_content.append(block)
        trimmed.append({**m, 'content': new_content})

    # Step 2: trim old turns if conversation is too long
    # Separate first user message (file/context) from the rest
    if len(trimmed) > _MAX_TURNS * 2 + 1:
        head = trimmed[:1]   # keep first message (file upload context)
        tail = trimmed[-((_MAX_TURNS * 2)):]
        trimmed = head + tail

    return trimmed


def run_agent_stream(messages: list):
    """
    Generator — yields JSON-encoded event strings for SSE.
    messages: list of {role, content} dicts (full conversation history).

    Event types emitted:
      {'type': 'text',       'text': str}          — streamed assistant text chunk
      {'type': 'tool_start', 'name': str}           — tool execution started
      {'type': 'tool_done',  'name': str, 'preview': str} — tool finished
      {'type': 'done',       'messages': list}      — conversation complete
      {'type': 'error',      'text': str}           — something went wrong
    """
    client = _get_client()
    current_messages = _trim_messages(list(messages))

    while True:
        # Retry loop for Anthropic rate-limit errors (max 3 attempts)
        for _attempt in range(3):
            try:
                with client.messages.stream(
                    model=MODEL,
                    max_tokens=8096,
                    system=SYSTEM_PROMPT,
                    tools=TOOL_DEFINITIONS,
                    messages=current_messages,
                ) as stream:
                    response = stream.get_final_message()
                break
            except anthropic.RateLimitError as exc:
                if _attempt == 2:
                    raise
                retry_after = int(exc.response.headers.get('retry-after', 20))
                yield json.dumps({'type': 'text', 'text': f'\n⏳ Anthropic rate limit — повтор через {retry_after}с...\n'})
                time.sleep(retry_after)

        # ── Tool-use turn ─────────────────────────────────────────────────────
        if response.stop_reason == 'tool_use':
            serialized = _serialize_content(response.content)

            # Emit any text Claude wrote before the tool call
            for block in response.content:
                if block.type == 'text' and block.text.strip():
                    yield json.dumps({'type': 'text', 'text': block.text})

            # Emit tool-start events
            for block in response.content:
                if block.type == 'tool_use':
                    yield json.dumps({'type': 'tool_start', 'name': block.name, 'input': block.input})

            current_messages.append({'role': 'assistant', 'content': serialized})

            # Execute tools and collect results
            tool_results = []
            for block in response.content:
                if block.type == 'tool_use':
                    try:
                        result = TOOL_FUNCTIONS[block.name](block.input)
                    except Exception as exc:
                        result = f'[Ошибка инструмента] {exc}'

                    yield json.dumps({
                        'type': 'tool_done',
                        'name': block.name,
                        'preview': result[:400],
                    })

                    tool_results.append({
                        'type': 'tool_result',
                        'tool_use_id': block.id,
                        'content': result,
                    })

            current_messages.append({'role': 'user', 'content': tool_results})
            continue  # Next loop iteration → Claude continues

        # ── Final text response ───────────────────────────────────────────────
        final_text = ''.join(
            b.text for b in response.content if hasattr(b, 'text')
        )

        # Yield in small chunks for smooth typing effect
        chunk = 8
        for i in range(0, len(final_text), chunk):
            yield json.dumps({'type': 'text', 'text': final_text[i:i + chunk]})

        current_messages.append({
            'role': 'assistant',
            'content': _serialize_content(response.content),
        })

        yield json.dumps({'type': 'done', 'messages': current_messages})
        break
